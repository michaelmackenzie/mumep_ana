#!/usr/bin/env python3
"""Median expected mu- --> e+ sensitivity under different RMC assumptions (the scale_rmc_* rateParams).

The mumep models split each RMC source (external, internal conversion) into its 0 and 1 neutron knockout samples,
normalized with the 0n fraction of RMC above 57 MeV, B(0) = 0.099 (Mu2ePhysics.C, physics.C), and B(1) = 1 - B(0).
Each scenario changes the RMC yields through the frozen rateParams of the model,

    scale_rmc_<src>_0n = B'(0) / B(0)              x  f_int (for src = int)
    scale_rmc_<src>_1n = (1 - B'(0)) / (1 - B(0))  x  f_int (for src = int)

where f_int is the scale of the internal conversion rate relative to the external one. The default scenarios shift
B(0) = 9.9 +- 1.9 (stat) +4.4 -3.3 (syst) % by its statistical and total (quadrature) uncertainty, f_int by +-10%,
and both together in the direction of more and of less background:

    nominal, b0_up, b0_down, int_up, int_down, b0_up_int_up, b0_down_int_down

For each scenario a background-only Asimov data set is generated from the generation card (default: the fit card)
with the shifted rates, and the limit is evaluated on it with the fit card at the same rates, i.e. the expected
sensitivity if the RMC is as assumed and modeled accordingly. --fit-nominal instead fits with the nominal RMC rates
(the RMC mismodeled by the shift). The RMC normalization nuisance (rmcN, or rmcNorm with a control region) stays
profiled as in the model. Parameters that a card does not have (e.g. the RMC of an envelope card) are not set in it.

    python3 rmc_assumption_scan.py models/mumep_40_r0106_hists/combined.txt
    python3 rmc_assumption_scan.py models/mumep_40_r0106_env/combined.txt \\
        --gen-card models/mumep_40_r0106_hists/combined.txt -j 4
    python3 rmc_assumption_scan.py models/mumep_40_r0106_hists/combined.txt --dry-run   # print the commands

The same Asimov data set is also fit with FitDiagnostics (background-only and s+b, r in the model's POI range), and
mu2ecombine.plots draws the pre/post-fit stacks, e.g. the envelope fit to the background generated by the histogram
model; the fitted r (s+b) shows any bias of the fit model. --no-fit-plots skips this.

Outputs: the Combine files, logs (logs/) and the results table (results.json) in rmc_scans/<tag>/ (-o); in
figures/rmc/<tag>/ (--fig-dir) the summary figure rmc_assumptions.png and, per scenario, <scenario>/<channel>_<fit>.png
(fit = prefit, fit_b, fit_s; log scale in <scenario>/log/) with postfit_yields.json. --plot-only remakes the table and
figures from results.json and the fitDiagnostics files. mu2ecombine must be importable (PYTHONPATH, see README).
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
import glob
import importlib.util
import json
import math
import os
import re
import subprocess
import sys

# 90% CL from SINDRUM II
PUBLISHED_LIMIT = {'mumem': 7.e-13, 'mumep': 1.7e-12}

# Allowed difference between the limit on the Asimov data set and the median of the expected bands
MAX_ASIMOV_MISMATCH = 0.05

# Combine jobs run one thread each, so -j counts cores
SINGLE_THREAD_ENV = dict(os.environ, OPENBLAS_NUM_THREADS='1', OMP_NUM_THREADS='1', MKL_NUM_THREADS='1')

RMC_SOURCES = ('ext', 'int')


def parse_limit(text, level=r'50\.0', unit=1.e-15):
    match = re.search(r"Expected " + level + r"%:\s*r\s*<\s*([\d\.eE+-]+)", text)
    return unit * float(match.group(1)) if match else -1.


def parse_observed(text, unit=1.e-15):
    """Observed limit; with the Asimov data set as the data, this is the median expected limit"""
    match = re.search(r"Observed Limit:\s*r\s*<\s*([\d\.eE+-]+)", text)
    return unit * float(match.group(1)) if match else -1.


def card_name(card):
    base = os.path.splitext(os.path.basename(card))[0]
    if base == 'combined':  # models/<name>/combined.txt, as written by build_model.py
        return os.path.basename(os.path.dirname(os.path.abspath(card)))
    for prefix in ['combine_total_', 'combine_']:
        if base.startswith(prefix):
            return base[len(prefix):]
    return base


def card_info(card):
    """Reference signal branching fraction (units of r), the discrete parameters, and the rateParam names of a card"""
    unit, discrete, rate_params = 1.e-15, [], set()
    with open(card) as f:
        for line in f:
            if line.startswith('# R_mue used for signal:'):
                unit = float(line.split(':')[1])
            tokens = line.split()
            if len(tokens) == 2 and tokens[1] == 'discrete':
                discrete.append(tokens[0])
            if len(tokens) >= 2 and tokens[1] == 'rateParam':
                rate_params.add(tokens[0])
    return unit, discrete, rate_params


def rmc_scales(b0, b0_nominal, f_int):
    """{rateParam: value} of the RMC knockout components for the 0n fraction b0 and internal conversion scale f_int"""
    knockout = {'0n': b0 / b0_nominal, '1n': (1. - b0) / (1. - b0_nominal)}
    return {f'scale_rmc_{src}_{n}': knockout[n] * (f_int if src == 'int' else 1.)
            for src in RMC_SOURCES for n in knockout}


def make_scenarios(args):
    """[(name, label, B(0), f_int)] of the RMC assumptions"""
    b0 = args.b0
    up = math.hypot(args.b0_stat, args.b0_syst_up)        # total, stat and syst in quadrature
    down = math.hypot(args.b0_stat, args.b0_syst_down)
    f = args.int_shift
    scenarios = [
        ('nominal',          'Nominal',                         b0,                1.),
        ('b0_up',            r'B(0) +1$\sigma$ (tot.)',         b0 + up,           1.),
        ('b0_down',          r'B(0) -1$\sigma$ (tot.)',         b0 - down,         1.),
        ('int_up',           f'Int. conv. +{100*f:g}%',         b0,                1. + f),
        ('int_down',         f'Int. conv. -{100*f:g}%',         b0,                1. - f),
        ('b0_up_int_up',     f'B(0) +1$\\sigma$, int. +{100*f:g}%', b0 + up,      1. + f),
        ('b0_down_int_down', f'B(0) -1$\\sigma$, int. -{100*f:g}%', b0 - down,    1. - f),
    ]
    if args.scenarios:
        wanted = [s.strip() for s in args.scenarios.split(',') if s.strip()]
        known = {s[0] for s in scenarios}
        unknown = [w for w in wanted if w not in known]
        if unknown:
            raise SystemExit(f'Unknown scenarios {unknown}; choose from {", ".join(s[0] for s in scenarios)}')
        scenarios = [s for s in scenarios if s[0] in wanted]
    for name, _, b0_s, f_s in scenarios:
        if not 0. < b0_s < 1. or f_s <= 0.:
            raise SystemExit(f'Scenario {name}: B(0) = {b0_s:.4f}, f_int = {f_s:.3f} is unphysical')
    return scenarios


def set_parameters(scales, available, extra):
    """--setParameters string of the scales the card has, plus the extra user parameters"""
    params = [f'{p}={v:.6g}' for p, v in sorted(scales.items()) if p in available]
    if extra: params.append(extra)
    return ','.join(params)


def parse_best_fit(text):
    """Best fit r of the s+b fit in FitDiagnostics: (r, err_lo, err_hi), or None"""
    match = re.search(r"Best fit r:\s*([\d\.eE+-]+)\s+-([\d\.eE+-]+)/\+([\d\.eE+-]+)", text)
    return tuple(float(g) for g in match.groups()) if match else None


def poi_range(card, default):
    """Range of r from the model.json next to the card (as build_model.py writes it), else default"""
    path = os.path.join(os.path.dirname(card), 'model.json')
    if os.path.isfile(path):
        with open(path) as f:
            pois = json.load(f).get('pois', {})
        if 'r' in pois: return tuple(pois['r'])
    return default


def find_mu2ecombine():
    """Directory holding the mu2ecombine package, found as build_model.py does: PYTHONPATH, $MU2ECOMBINE_DIR, or a
    Mu2eEvtAna clone next to this repository (<Mu2eEvtAna>/combine); None if there is none"""
    spec = importlib.util.find_spec('mu2ecombine')
    if spec is not None and spec.submodule_search_locations:
        return os.path.dirname(list(spec.submodule_search_locations)[0])
    here = os.path.dirname(os.path.abspath(__file__))
    for path in [os.environ.get('MU2ECOMBINE_DIR', ''),
                 os.path.normpath(os.path.join(here, '..', '..', '..', 'Mu2eEvtAna', 'combine'))]:
        if path and os.path.isdir(os.path.join(path, 'mu2ecombine')):
            return os.path.abspath(path)
    return None


def mu2ecombine_env():
    """Environment for the mu2ecombine.plots subprocess, with mu2ecombine on its PYTHONPATH, or None"""
    package_dir = find_mu2ecombine()
    if package_dir is None: return None
    return dict(SINGLE_THREAD_ENV, PYTHONPATH=os.pathsep.join([package_dir, os.environ.get('PYTHONPATH', '')]))


def run(command, log, cwd, env=SINGLE_THREAD_ENV):
    result = subprocess.run(command, shell=True, cwd=cwd, env=env, stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, text=True)
    with open(log, 'w') as f:
        f.write(command + '\n\n' + result.stdout)
    return result.returncode, result.stdout


def main():
    parser = argparse.ArgumentParser(description='Median expected sensitivity under different RMC assumptions',
                                     formatter_class=argparse.RawDescriptionHelpFormatter, epilog=__doc__)
    parser.add_argument('card', help='Combine card used in the fit, e.g. models/mumep_40_r0106_hists/combined.txt')
    parser.add_argument('--gen-card', default=None, help='Card used to generate the Asimov data set (default: the fit card)')
    parser.add_argument('--b0', type=float, default=0.099, help='Nominal 0n fraction B(0) of the model (default: %(default)s)')
    parser.add_argument('--b0-stat', type=float, default=0.019, help='Statistical uncertainty of B(0) (default: %(default)s)')
    parser.add_argument('--b0-syst-up', type=float, default=0.044, help='Upper systematic uncertainty of B(0) (default: %(default)s)')
    parser.add_argument('--b0-syst-down', type=float, default=0.033, help='Lower systematic uncertainty of B(0) (default: %(default)s)')
    parser.add_argument('--int-shift', type=float, default=0.10,
                        help='Relative shift of the internal conversion rate (default: %(default)s)')
    parser.add_argument('--scenarios', default=None, help='Comma-separated subset of the scenarios (default: all)')
    parser.add_argument('--fit-nominal', action='store_true',
                        help='Fit with the nominal RMC rates (generate shifted, fit nominal) instead of the shifted ones')
    parser.add_argument('--gen-params', default='', help='Extra --setParameters for the generation')
    parser.add_argument('--fit-params', default='', help='Extra --setParameters for the fit')
    parser.add_argument('--gen-args', default='', help='Additional arguments for the generation')
    parser.add_argument('--fit-args', default='', help='Additional arguments for the fit')
    parser.add_argument('-T', '--tag', default=None, help='Tag for the outputs (default: the fit card name)')
    parser.add_argument('-j', '--threads', type=int, default=1, help='Scenarios run in parallel (default: %(default)s)')
    parser.add_argument('-o', '--out-dir', default=None, help='Combine outputs, logs and results (default: rmc_scans/<tag>)')
    parser.add_argument('--fig-dir', default=None, help='Directory for the figure (default: figures/rmc/<tag>)')
    parser.add_argument('--no-fit-plots', action='store_true',
                        help='Skip the FitDiagnostics fit and its pre/post-fit figures (figures/rmc/<tag>/<scenario>/)')
    parser.add_argument('--dry-run', action='store_true', help='Print the scale factors and Combine commands only')
    parser.add_argument('--plot-only', action='store_true', help='Only remake the table and figure from <out-dir>/results.json')
    args = parser.parse_args()

    if not 0. < args.b0 < 1.: parser.error('--b0 must be in (0, 1)')
    if args.threads < 1: parser.error('--threads must be >= 1')
    if args.threads > 20: print(f'WARNING: {args.threads} parallel Combine jobs, more than 20 cores on a shared node')

    card = os.path.abspath(args.card)   # absolute: Combine runs in the output directory
    gen_card = os.path.abspath(args.gen_card) if args.gen_card else card
    for c in [card, gen_card]:
        if not os.path.isfile(c): parser.error(f'card {c} does not exist')
    tag = args.tag or card_name(card) + ('_fitnom' if args.fit_nominal else '')
    out_dir = os.path.abspath(args.out_dir or os.path.join('rmc_scans', tag))
    fig_dir = os.path.abspath(args.fig_dir or os.path.join('figures', 'rmc', tag))
    log_dir = os.path.join(out_dir, 'logs')
    results_file = os.path.join(out_dir, 'results.json')
    signal = 'mumem' if 'mumem' in card_name(card) else 'mumep'
    r_range = 100. if signal == 'mumem' else 500.

    unit, discrete, fit_rate_params = card_info(card)
    gen_unit, _, gen_rate_params = card_info(gen_card)
    if gen_unit != unit:
        print(f'WARNING: the cards use different reference branching fractions ({gen_unit:.3e} vs. {unit:.3e})')
    rmc_params = set(rmc_scales(args.b0, args.b0, 1.))
    missing = rmc_params - gen_rate_params
    if missing:
        parser.error(f'the generation card {gen_card} has no {", ".join(sorted(missing))}: the RMC shifts need the'
                     ' 0n/1n split of the mumep models')
    if not rmc_params & fit_rate_params:
        print('NOTE: the fit card has no scale_rmc_* rateParams (e.g. an envelope); the shifts enter the generation only')

    scenarios = make_scenarios(args)

    gen_command = f'combine -M GenerateOnly -d {gen_card} -t -1 --expectSignal 0 --saveToys -s 123456 {args.gen_args}'
    minimizer = ' --cminApproxPreFitTolerance 0.1 --cminPreScan --cminPreFit 1'
    if discrete:
        # Discretely profiled envelope: every function tried in each fit, strategy 1 (see sensitivity_vs_livetime.py)
        minimizer += (' --cminDefaultMinimizerStrategy=1 --cminRunAllDiscreteCombinations'
                      ' --X-rtd REMOVE_CONSTANT_ZERO_POINT=1 --X-rtd MINIMIZER_freezeDisassociatedParams'
                      ' --X-rtd MINIMIZER_multiMin_hideConstants')
    else:
        minimizer += ' --cminDefaultMinimizerStrategy=0'
    fit_command = (f'combine -M AsymptoticLimits -d {card} --rMin 0. --rMax {r_range} -t -1 --cl 0.9'
                   f' --rAbsAcc 0.01 --rRelAcc 0.01{minimizer} {args.fit_args}')
    # Background-only and s+b fits of the same Asimov data set, with the shapes for the pre/post-fit figures.
    # r may go negative here (the model's POI range), unlike in the limit
    r_lo, r_hi = poi_range(card, (-r_range, r_range))
    diag_command = (f'combine -M FitDiagnostics -d {card} -t -1 --rMin {r_lo:g} --rMax {r_hi:g}{minimizer}'
                    f' --saveShapes --saveWithUncertainties {args.fit_args}')
    fit_model_dir = os.path.dirname(card)
    fit_plots = not args.no_fit_plots
    plot_env = mu2ecombine_env() if fit_plots else None
    if fit_plots and not os.path.isfile(os.path.join(fit_model_dir, 'model.json')):
        print(f'WARNING: no model.json next to {card} (not a build_model.py model): no pre/post-fit figures')
        fit_plots = False
    elif fit_plots and plot_env is None:
        print('WARNING: mu2ecombine not found (PYTHONPATH, MU2ECOMBINE_DIR, or ../../../Mu2eEvtAna/combine):'
              ' no pre/post-fit figures')
        fit_plots = False

    def plot_commands(run_name, name):
        """mu2ecombine.plots commands of a scenario's FitDiagnostics output: linear and log scale"""
        diag_file = os.path.join(out_dir, f'fitDiagnostics.{run_name}.root')
        base = f'{sys.executable} -m mu2ecombine.plots {diag_file} --model-dir {fit_model_dir}'
        return diag_file, [f'{base} --figdir {os.path.join(fig_dir, name)}',
                           f'{base} --figdir {os.path.join(fig_dir, name, "log")} --logy']

    def make_fit_plots(run_name, name):
        """Pre/post-fit figures of a scenario; returns the warnings"""
        diag_file, plots = plot_commands(run_name, name)
        if not os.path.isfile(diag_file): return [f'{name}: WARNING - no {diag_file}, no pre/post-fit figures']
        warnings = []
        for i, command in enumerate(plots):
            status, text = run(command, os.path.join(log_dir, f'{run_name}_plots{"_log" if i else ""}.log'),
                               out_dir, plot_env)
            if status != 0: warnings += [f'{name}: WARNING - pre/post-fit figures failed', command, text]
        return warnings

    def commands(name, b0, f_int):
        scales = rmc_scales(b0, args.b0, f_int)
        fit_scales = rmc_scales(args.b0, args.b0, 1.) if args.fit_nominal else scales
        run_name = f'rmc_{tag}_{name}'
        gen = gen_command + f' -n .{run_name}'
        gen_params = set_parameters(scales, gen_rate_params, args.gen_params)
        if gen_params: gen += f' --setParameters {gen_params}'
        fit = fit_command + f' -n .{run_name} --toysFile=TOYFILE'
        diag = diag_command + f' -n .{run_name} --toysFile=TOYFILE'
        fit_params = set_parameters(fit_scales, fit_rate_params, args.fit_params)
        if fit_params:
            fit += f' --setParameters {fit_params}'
            diag += f' --setParameters {fit_params}'
        return run_name, scales, gen, fit, diag

    def scan_point(scenario):
        name, _, b0, f_int = scenario
        run_name, scales, gen, fit, diag = commands(name, b0, f_int)
        messages = []
        toy_pattern = os.path.join(out_dir, f'higgsCombine.{run_name}.GenerateOnly.mH120*.root')
        for old in glob.glob(toy_pattern): os.remove(old)
        status, text = run(gen, os.path.join(log_dir, run_name + '_gen.log'), out_dir)
        toy_files = glob.glob(toy_pattern)
        if status != 0 or not toy_files:
            return None, [f'{name}: WARNING - failed to generate the Asimov data set', gen, text]
        fit = fit.replace('TOYFILE', toy_files[0])
        status, text = run(fit, os.path.join(log_dir, run_name + '_fit.log'), out_dir)
        median = parse_observed(text, unit)
        if median <= 0.:
            return None, [f'{name}: WARNING - failed to parse the median expected limit', fit, text]
        bands = parse_limit(text, r'50\.0', unit)
        if bands > 0. and abs(median / bands - 1.) > MAX_ASIMOV_MISMATCH:
            messages.append(f'{name}: WARNING - Asimov limit {median:.3e} differs from the median of the bands'
                            f' {bands:.3e} by more than {100*MAX_ASIMOV_MISMATCH:.0f}%')
        limits = dict(median=median,
                      up_1=parse_limit(text, r'84\.0', unit), up_2=parse_limit(text, r'97\.5', unit),
                      down_1=parse_limit(text, r'16\.0', unit), down_2=parse_limit(text, r' 2\.5', unit))
        point = dict(name=name, b0=b0, f_int=f_int, scales=scales, limits=limits)
        summary = f'{name}: limit = {median:.3e}'

        # Fit the same Asimov data set for the pre/post-fit figures and the fitted r
        if not args.no_fit_plots:
            diag = diag.replace('TOYFILE', toy_files[0])
            for old in glob.glob(os.path.join(out_dir, f'fitDiagnostics.{run_name}.root')): os.remove(old)
            status, text = run(diag, os.path.join(log_dir, run_name + '_diag.log'), out_dir)
            best = parse_best_fit(text)
            if status != 0:
                messages += [f'{name}: WARNING - FitDiagnostics failed (see logs/{run_name}_diag.log)']
            elif best is None:
                messages += [f'{name}: WARNING - no fitted r in logs/{run_name}_diag.log']
            else:
                point['r_fit'] = dict(value=best[0], err_lo=best[1], err_hi=best[2])
                summary += f', fitted r = {best[0]:.3g} -{best[1]:.2g}/+{best[2]:.2g}'
            if fit_plots: messages += make_fit_plots(run_name, name)
        messages.append(summary)
        return point, messages

    if args.dry_run:
        for name, label, b0, f_int in scenarios:
            run_name, scales, gen, fit, diag = commands(name, b0, f_int)
            print(f'# {name}: B(0) = {100*b0:.2f}%, f_int = {f_int:.3f}; '
                  + ', '.join(f'{p} = {v:.4f}' for p, v in sorted(scales.items())))
            print(gen)
            print(fit)
            if not args.no_fit_plots:
                print(diag)
                if fit_plots: print('\n'.join(plot_commands(run_name, name)[1]))
            print()
        print(f'(run in {out_dir})')
        return

    if args.plot_only:
        if not os.path.isfile(results_file): parser.error(f'--plot-only: {results_file} does not exist')
        with open(results_file) as f:
            points = json.load(f)['points']
        if fit_plots:   # remake the pre/post-fit figures of the scenarios that have a FitDiagnostics output
            os.makedirs(log_dir, exist_ok=True)
            for p in points:
                warnings = make_fit_plots(f'rmc_{tag}_{p["name"]}', p['name'])
                if warnings: print('\n'.join(warnings[:1]))
    else:
        print(f'Generating with {gen_card}, fitting with {card}' +
              (' at the nominal RMC rates' if args.fit_nominal else '') +
              (f' (envelope index {", ".join(discrete)})' if discrete else ''))
        os.makedirs(log_dir, exist_ok=True)
        if args.threads > 1:
            with ThreadPoolExecutor(max_workers=args.threads) as pool:
                results = list(pool.map(scan_point, scenarios))
        else:
            results = [scan_point(s) for s in scenarios]
        points = []
        for point, messages in results:
            print('\n'.join(messages), flush=True)
            if point is not None: points.append(point)
        with open(results_file, 'w') as f:
            json.dump(dict(fit_card=card, gen_card=gen_card, unit=unit, fit_nominal=args.fit_nominal,
                           b0=args.b0, b0_stat=args.b0_stat, b0_syst_up=args.b0_syst_up,
                           b0_syst_down=args.b0_syst_down, int_shift=args.int_shift, points=points), f, indent=1)
        print(f'Results in {results_file}')

    if not points:
        print('No scenario succeeded')
        return
    labels = {s[0]: s[1] for s in make_scenarios(argparse.Namespace(**{**vars(args), 'scenarios': None}))}
    nominal = next((p['limits']['median'] for p in points if p['name'] == 'nominal'), None)

    # Table
    print(f'\n{"scenario":<18} {"B(0) [%]":>8} {"f_int":>6} {"s_0n":>7} {"s_1n":>7} {"median":>10} {"/nominal":>9}'
          f' {"-1sd":>10} {"+1sd":>10} {"fitted r":>16}')
    for p in points:
        lim, s = p['limits'], p['scales']
        ratio = f'{lim["median"]/nominal:9.3f}' if nominal else f'{"-":>9}'
        print(f'{p["name"]:<18} {100*p["b0"]:8.2f} {p["f_int"]:6.2f} {s["scale_rmc_ext_0n"]:7.3f}'
              f' {s["scale_rmc_ext_1n"]:7.3f} {lim["median"]:10.3e} {ratio} {lim["down_1"]:10.3e} {lim["up_1"]:10.3e}'
              + (f' {rf["value"]:7.3g} -{rf["err_lo"]:.2g}/+{rf["err_hi"]:.2g}' if (rf := p.get('r_fit')) else ''))
    if nominal:
        print(f'Nominal: {PUBLISHED_LIMIT[signal]/nominal:.1f} x below the SINDRUM II limit')

    # Figure: median expected limit of each scenario with its +-1 sigma band
    try:
        import matplotlib
    except ImportError:
        print('WARNING: no matplotlib (set up pyenv rootana), no figure; remake it with --plot-only')
        return
